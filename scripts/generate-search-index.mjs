/* Regenerates the docs search index. Run via `npm run search-index`.

   The anchors that section results scroll to are produced at runtime from
   translated headings, so they cannot be written by hand without going stale.
   This script renders every page in every language and every tab and reads the
   ids the pages actually render. */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { installDomEnvironment } from './domEnvironment.mjs'

installDomEnvironment()

const { buildSearchIndex, installDomStubs } = await import('./buildSearchIndex.jsx')
installDomStubs()

const { pageEntries, sectionEntries } = await buildSearchIndex()

const KEY_ORDER = ['id', 'lang', 'type', 'pageTitle', 'section', 'route', 'anchor', 'tab', 'tabLabel']

const serialize = (entry) =>
  `  { ${KEY_ORDER.filter((key) => entry[key] !== undefined)
    .map((key) => `${key}: ${JSON.stringify(entry[key])}`)
    .join(', ')} },`

const banner = (name) => `// Generated by \`npm run search-index\` — do not edit by hand.
// Anchors come from the rendered pages and differ per language.
export const ${name} = [`

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

writeFileSync(
  resolve(root, 'src/config/sectionData.js'),
  `${banner('sectionData')}\n${sectionEntries.map(serialize).join('\n')}\n]\n`,
)

writeFileSync(
  resolve(root, 'src/config/searchData.js'),
  `// Generated by \`npm run search-index\` — do not edit by hand.
// Page and tab level hits; section level hits live in sectionData.js.
import { sectionData } from './sectionData'

const pageData = [
${pageEntries.map(serialize).join('\n')}
]

export const searchData = [...pageData, ...sectionData]
`,
)

console.log(`search index: ${pageEntries.length} page/tab entries, ${sectionEntries.length} section entries`)
